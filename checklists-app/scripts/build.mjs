// Build step (runs locally and on Netlify):
//  1. copies the shared checklist screens + base styles + logo from the main app;
//  2. lists the loading-screen images in public/splash/ into public/splash/list.js,
//     so adding a picture is just dropping a file into that folder.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
const pub = path.resolve(here, '..', 'public');

const out = path.join(pub, 'shared');
fs.mkdirSync(out, { recursive: true });
for (const f of ['checklists.js', 'styles.css', 'logo.png']) fs.copyFileSync(path.join(root, 'public', f), path.join(out, f));
console.log('shared files copied to public/shared');

export function buildSplashList(dir = path.join(pub, 'splash')) {
  fs.mkdirSync(dir, { recursive: true });
  const images = fs.readdirSync(dir)
    .filter(f => /\.(jpe?g|png|webp|avif)$/i.test(f) && !f.startsWith('.'))
    .sort()
    .map(f => `/splash/${encodeURIComponent(f)}`);
  fs.writeFileSync(path.join(dir, 'list.js'),
    `// generated by scripts/build.mjs – do not edit; add or remove images in this folder instead\nwindow.SPLASH_IMAGES = ${JSON.stringify(images, null, 2)};\n`);
  return images;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const images = buildSplashList();
  console.log(`loading screen: ${images.length} image(s)`);
}
